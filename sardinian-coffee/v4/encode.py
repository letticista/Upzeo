"""Turn the rendered frames into the final 1080x1920 vertical MP4 with title, light grade and the synthesized soundtrack.

    blender -b --factory-startup -P v4/encode.py -- [--fps 60] [--out sardinian_coffee_outro_v4.mp4]
    python3 v4/encode.py -- --frames v4/frames_draft --scale 0.5 --out draft.mp4     (a draft from low-res frames)
    (or: python3 v4/encode.py -- ...)

Needs FFmpeg on the PATH. The soundtrack is generated by FFmpeg sources and filters only (no audio files).
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else sys.argv[1:]
ap = argparse.ArgumentParser()
ap.add_argument('--fps', type=int, default=60)
ap.add_argument('--out', default=str(ROOT / 'sardinian_coffee_outro_v4.mp4'))
ap.add_argument('--crf', type=int, default=16)
ap.add_argument('--frames', default=str(HERE / 'frames'))
ap.add_argument('--scale', type=float, default=1.0, help='size of the frames relative to 1080x1920 (for drafts)')
args = ap.parse_args(argv)

DUR = 12.0
W, H = 2 * round(540 * args.scale), 2 * round(960 * args.scale)
# keep in step with T in coffee/common.py
BURRS, DOSE, TAMP, EXTRACT, CUP, REVEAL, TAG, FADE = 1.0, 2.6, 3.62, 4.0, 7.2, 8.75, 9.75, 10.8


def reed(f):
    return (f'(sin(2*PI*{f}*t)+0.35*sin(4*PI*{f}*t)+0.6*sin(6*PI*{f}*t)+0.2*sin(8*PI*{f}*t)'
            f'+0.32*sin(10*PI*{f}*t)+0.12*sin(12*PI*{f}*t)+0.18*sin(14*PI*{f}*t))')


def launeddas(start):
    """Mancosa line over the tumbu drone, in A (Sardinian triple clarinet)."""
    N = {'A4': 440, 'B4': 493.88, 'C5s': 554.37, 'D5': 587.33, 'E5': 659.26, 'F5s': 739.99}
    seq = ['E5', 'C5s', 'D5', 'E5', 'F5s', 'E5', 'D5', 'C5s', 'E5', 'C5s', 'D5', 'E5', 'C5s', 'B4', 'A4', 'C5s', 'E5', 'F5s',
           'E5', 'D5', 'C5s', 'B4', 'C5s', 'D5', 'E5', 'D5', 'C5s', 'B4', 'A4', 'B4']
    step = 0.1
    terms = []
    for i, n in enumerate(seq):
        s, e = start + i * step, start + i * step + step * 0.93
        terms.append(f'if(between(t,{s:.3f},{e:.3f}),min(1,(t-{s:.3f})*220)*min(1,({e:.3f}-t)*140)*{reed(N[n])},0)')
    ls = start + len(seq) * step
    terms.append(f'if(between(t,{ls:.3f},11.98),min(1,(t-{ls:.3f})*60)*min(1,(11.98-t)*1.2)*({reed(440)}+0.7*{reed(659.26)}),0)')
    return '+'.join(terms)


def drop_events():
    p = HERE / 'cache' / 'extract_events.json'
    if p.exists():
        ev = json.loads(p.read_text())
        return ev.get('drops', []), ev.get('stream_hit', EXTRACT + 1.2)
    return [EXTRACT + 0.5, EXTRACT + 0.8, EXTRACT + 1.0], EXTRACT + 1.2


def audio_graph():
    T = DUR
    drops, hit = drop_events()
    plinks = '+'.join(f'if(gte(t,{t0:.3f}),0.3*sin(2*PI*({700 + 90 * (i % 5)}*(t-{t0:.3f})-2600*pow(t-{t0:.3f},2)))*exp(-36*(t-{t0:.3f})),0)'
                      for i, t0 in enumerate(drops[:24])) or '0'
    return ';'.join([
        f"anoisesrc=d={T}:c=brown:r=48000:a=0.6:seed=2,lowpass=f=700,volume='0.35*exp(-pow((t-0.5)/0.6,2))':eval=frame[air]",
        # grinder motor (slowed down with the picture) and the beans cracking against the burrs
        f"aevalsrc='0.1*between(t,{BURRS},{DOSE})*min(1,(t-{BURRS})*20)*min(1,({DOSE}-t)*20)*(sin(2*PI*(92*(t-{BURRS})))+0.5*sin(4*PI*(92*(t-{BURRS})))+0.33*sin(6*PI*(92*(t-{BURRS}))))':s=48000:d={T},lowpass=f=2400[motor]",
        f"aevalsrc='between(t,{BURRS + 0.35},{DOSE})*if(lt(random(0),0.004+0.02*max(t-{BURRS + 0.35},0)),(random(1)-0.5)*2.4,0)':s=48000:d={T},bandpass=f=2300:width_type=o:w=2,volume=0.9[crunch]",
        f"anoisesrc=d={T}:c=pink:r=48000:a=0.6:seed=4,bandpass=f=1400:width_type=o:w=2.2,"
        f"volume='0.8*exp(-pow((t-{DOSE - 0.04})/0.11,2))+0.45*exp(-pow((t-{CUP - 0.05})/0.13,2))+0.35*exp(-pow((t-8.1)/0.45,2))+0.35*exp(-pow((t-{TAMP - 0.1})/0.08,2))+0.25*exp(-pow((t-{BURRS})/0.1,2))+0.3*exp(-pow((t-{EXTRACT})/0.1,2))':eval=frame,aphaser=type=t:speed=1.6:decay=0.45[whoosh]",
        f"anoisesrc=d={T}:c=pink:r=48000:a=0.5:seed=6,highpass=f=2800,lowpass=f=9000,volume='0.3*between(t,{DOSE},{TAMP - 0.3})*min(1,(t-{DOSE})*8)*min(1,({TAMP - 0.3}-t)*6)*(0.7+0.3*sin(2*PI*23*t))':eval=frame[pour]",
        f"aevalsrc='if(gte(t,{TAMP}),0.9*sin(2*PI*(62*(t-{TAMP})+40*(1-exp(-30*(t-{TAMP})))/30))*exp(-7*(t-{TAMP})),0)':s=48000:d={T}[thud]",
        f"anoisesrc=d={T}:c=white:r=48000:a=1:seed=8,bandpass=f=3200:width_type=o:w=1.5,volume='if(gte(t,{TAMP}),0.75*exp(-60*(t-{TAMP})),0)':eval=frame[click]",
        f"aevalsrc='0.065*between(t,{EXTRACT},{CUP})*min(1,(t-{EXTRACT})*10)*min(1,({CUP}-t)*10)*(sin(2*PI*50*t)+0.6*sin(2*PI*100*t)+0.35*sin(2*PI*150*t))':s=48000:d={T},lowpass=f=500[pump]",
        f"anoisesrc=d={T}:c=pink:r=48000:a=0.7:seed=9,bandpass=f=850:width_type=o:w=1.4,volume='0.48*between(t,{hit:.3f},{CUP - 0.02})*min(1,(t-{hit:.3f})*3)*min(1,({CUP - 0.02}-t)*12)*(0.55+0.45*sin(2*PI*6.3*t)*sin(2*PI*2.7*t))':eval=frame,tremolo=f=13:d=0.35[trickle]",
        f"aevalsrc='{plinks}':s=48000:d={T}[drips]",
        f"aevalsrc='(0.03+0.06*min(1,t/{CUP})+0.035*between(t,{REVEAL},{T}))*min(1,({T}-t)*2.5)*({reed(110)}+0.8*{reed(110.35)}+0.45*{reed(220)})':s=48000:d={T},lowpass=f=1800,equalizer=f=700:width_type=o:w=1.2:g=4[drone]",
        f"aevalsrc='0.08*({launeddas(CUP + 0.1)})':s=48000:d={T},highpass=f=250,equalizer=f=1250:width_type=o:w=1:g=5,lowpass=f=6500,aecho=0.6:0.35:90:0.25[melody]",
        "aevalsrc='" + '+'.join(f'if(gte(t,{t0}),0.11*(sin(2*PI*{f}*(t-{t0}))+0.4*sin(2*PI*{f * 2.76:.2f}*(t-{t0})))*exp(-2.6*(t-{t0})),0)'
                                 for t0, f in [(REVEAL, 880), (REVEAL + 0.18, 1318.51), (REVEAL + 0.4, 1760), (REVEAL + 0.68, 2217.46), (TAG, 1318.51)])
        + f"':s=48000:d={T},aecho=0.7:0.5:120|240:0.3|0.2[chime]",
        f"aevalsrc='if(gte(t,{TAG}),0.7*(sin(2*PI*44*(t-{TAG}))+0.4*sin(2*PI*88*(t-{TAG})))*exp(-1.3*(t-{TAG}))*min(1,(t-{TAG})*40),0)':s=48000:d={T}[hit]",
        "[air][motor][crunch][whoosh][pour][thud][click][pump][trickle][drips][drone][melody][chime][hit]amix=inputs=14:normalize=0,"
        "highpass=f=28,acompressor=threshold=0.3:ratio=2.5:attack=4:release=140,"
        f"afade=t=in:st=0:d=0.1,afade=t=out:st={FADE}:d={DUR - FADE},alimiter=limit=0.9,aformat=channel_layouts=stereo[aout]",
    ])


def video_graph():
    fps = args.fps
    rise = round(16 * args.scale)  # px the title drifts up while it appears
    return ';'.join([
        f'[0:v]scale={W}:{H}:flags=lanczos,format=rgb48le,vignette=angle=PI/5:mode=forward,noise=c0s=4:c0f=t,format=rgb24[base]',
        # dark gradient behind the title
        f"[2:v]scale={W}:{H}:flags=bicubic,format=rgba,fade=t=in:st={TAG - 0.5}:d=0.8:alpha=1[shade]",
        f"[1:v]scale={W}:{H}:flags=lanczos,format=rgba,fade=t=in:st={TAG}:d=0.45:alpha=1[title]",
        f"[base][shade]overlay=0:0[b1]",
        f"[b1][title]overlay=x=0:y='{rise}*(1-min(1,max(0,(t-{TAG})/0.6)))'[b2]",
        f"[b2]fade=t=in:st=0:d=0.25,fade=t=out:st={FADE}:d={DUR - FADE},format=yuv420p[vout]",
    ])


def main():
    frames = Path(args.frames)
    title = HERE / 'cache' / 'tagline.png'
    cmd = ['ffmpeg', '-hide_banner', '-y',
           '-framerate', str(args.fps), '-i', str(frames / 'f_%05d.png'),
           '-loop', '1', '-framerate', str(args.fps), '-t', str(DUR), '-i', str(title),
           '-loop', '1', '-framerate', str(args.fps), '-t', str(DUR), '-i', str(HERE / 'cache' / 'shade.png'),
           '-filter_complex', video_graph() + ';' + audio_graph(),
           '-map', '[vout]', '-map', '[aout]',
           '-c:v', 'libx264', '-preset', 'slow', '-crf', str(args.crf), '-profile:v', 'high', '-level', '4.2', '-pix_fmt', 'yuv420p',
           '-r', str(args.fps), '-g', str(args.fps * 2), '-movflags', '+faststart',
           '-c:a', 'aac', '-b:a', '256k', '-ar', '48000', '-t', str(DUR), args.out]
    print('[encode]', ' '.join(cmd[:8]), '...', flush=True)
    subprocess.run(cmd, check=True)
    print(f'[encode] wrote {args.out}', flush=True)


if __name__ == '__main__':
    main()
